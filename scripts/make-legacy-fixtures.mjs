/**
 * Writes tests/e2e/fixtures/game1-saves.ts: Tokenmaxxing 1 saves produced by
 * game 1's *own* signing code, so the legacy-import e2e spec tests the sequel
 * against what game 1 really writes, without needing game 1 checked out.
 *
 *   node scripts/make-legacy-fixtures.mjs   # needs ../tokenmaxxing next to this repo
 *
 * Re-run it only if game 1's save format ever changes.
 */
import { writeFileSync } from 'node:fs';
import * as game1 from '../../tokenmaxxing/src/sim/save.ts';

function save(edit = () => {}) {
  const store = new Map();
  const storage = {
    getItem: (k) => store.get(k) ?? null,
    setItem: (k, v) => void store.set(k, v),
    removeItem: (k) => void store.delete(k),
  };
  const meta = game1.defaultMeta();
  meta.runs = 7;
  meta.wins = 2;
  meta.bestProject = 6;
  meta.demos = 4;
  meta.totalDemosEarned = 30;
  meta.levels['unlock_swarm'] = 1;
  meta.levels['cracked'] = 2;
  meta.achievements = { first_ship: 1, series_a: 3 };
  edit(meta);
  if (!game1.saveMeta(meta, storage)) throw new Error('game 1 refused to write the save');
  return store.get(game1.SAVE_KEY);
}

const clean = save();
// Hand-edited after signing: more wins than it earned.
const tampered = (() => {
  const raw = JSON.parse(clean);
  raw['wins'] = 5;
  return JSON.stringify(raw);
})();
// Correctly re-signed with game 1's code, but impossible: more wins than runs.
const forged = (() => {
  const raw = JSON.parse(clean);
  raw['wins'] = 50;
  raw['sig'] = game1.signSave(raw);
  return JSON.stringify(raw);
})();
// A clean signature over a save that carries game 1's own cheating badge.
const convicted = save((m) => {
  m.achievements = { ...m.achievements, script_kiddie: 2 };
});

const verdicts = Object.fromEntries(
  Object.entries({ clean, tampered, forged, convicted }).map(([k, raw]) => [k, game1.auditSave(JSON.parse(raw))]),
);

const out = `/**
 * GENERATED by scripts/make-legacy-fixtures.mjs from Tokenmaxxing 1's own
 * save code. Do not edit by hand: re-run the script instead.
 */
export const GAME1_SAVE_KEY = ${JSON.stringify(game1.SAVE_KEY)};

export const GAME1_SAVES = {
  clean: ${JSON.stringify(clean)},
  tampered: ${JSON.stringify(tampered)},
  forged: ${JSON.stringify(forged)},
  convicted: ${JSON.stringify(convicted)},
} as const;

/** What game 1's own auditSave said about each, when they were generated. */
export const GAME1_VERDICTS = ${JSON.stringify(verdicts)} as const;
`;
writeFileSync(new URL('../tests/e2e/fixtures/game1-saves.ts', import.meta.url), out);
console.log('wrote tests/e2e/fixtures/game1-saves.ts', verdicts);
